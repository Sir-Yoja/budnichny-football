-- Durable effect history and per-user notification read state.
create table if not exists public.player_effect_events (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  effect_type text not null check (effect_type in ('debuff_enabled','debuff_disabled','debuff_auto_cleared')),
  amount numeric(5,2) not null default 0 check (amount >= 0 and amount <= 10),
  source text not null default 'admin' check (source in ('admin','attendance')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists player_effect_events_player_created_idx
  on public.player_effect_events(player_id, created_at desc);
alter table public.player_effect_events enable row level security;
drop policy if exists player_effect_events_public_read on public.player_effect_events;
create policy player_effect_events_public_read on public.player_effect_events
  for select to anon, authenticated using (true);
drop policy if exists player_effect_events_admin_insert on public.player_effect_events;
create policy player_effect_events_admin_insert on public.player_effect_events
  for insert to authenticated with check (public.is_site_admin());

create or replace function public.log_player_debuff_transition()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  event_source text := coalesce(nullif(current_setting('app.debuff_event_source', true), ''), 'admin');
begin
  if old.debuff_enabled is distinct from new.debuff_enabled then
    if new.debuff_enabled then
      insert into public.player_effect_events(player_id,effect_type,amount,source,details)
      values(new.id,'debuff_enabled',coalesce(new.debuff_amount,0),'admin',
        jsonb_build_object('previous_amount',coalesce(old.debuff_amount,0)));
    else
      insert into public.player_effect_events(player_id,effect_type,amount,source,details)
      values(new.id,
        case when event_source='attendance' then 'debuff_auto_cleared' else 'debuff_disabled' end,
        coalesce(old.debuff_amount,0),event_source,
        jsonb_build_object('new_amount',coalesce(new.debuff_amount,0)));
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists players_log_debuff_transition on public.players;
create trigger players_log_debuff_transition
  after update of debuff_enabled on public.players
  for each row execute function public.log_player_debuff_transition();

create or replace function public.clear_player_debuff_after_attendance(p_player_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_site_admin() then
    raise exception 'admin_required';
  end if;
  perform set_config('app.debuff_event_source','attendance',true);
  update public.players
    set debuff_enabled=false, debuff_amount=0
    where id=p_player_id and debuff_enabled=true;
  return found;
end;
$$;
revoke all on function public.clear_player_debuff_after_attendance(bigint) from public, anon;
grant execute on function public.clear_player_debuff_after_attendance(bigint) to authenticated;

create table if not exists public.player_notification_reads (
  user_id uuid not null references auth.users(id) on delete cascade,
  submission_id bigint not null references public.game_player_stat_submissions(id) on delete cascade,
  read_at timestamptz not null default now(),
  primary key(user_id, submission_id)
);
alter table public.player_notification_reads enable row level security;
drop policy if exists player_notification_reads_select_own on public.player_notification_reads;
create policy player_notification_reads_select_own on public.player_notification_reads
  for select to authenticated using (user_id=auth.uid());
drop policy if exists player_notification_reads_insert_own on public.player_notification_reads;
create policy player_notification_reads_insert_own on public.player_notification_reads
  for insert to authenticated with check (user_id=auth.uid());
drop policy if exists player_notification_reads_delete_own on public.player_notification_reads;
create policy player_notification_reads_delete_own on public.player_notification_reads
  for delete to authenticated using (user_id=auth.uid());
